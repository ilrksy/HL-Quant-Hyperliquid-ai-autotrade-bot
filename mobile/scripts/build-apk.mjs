// builds an installable apk and copies it to ../release: a signed release apk when ANDROID_KEYSTORE_PATH is set, otherwise a debug apk
// usage: node scripts/build-apk.mjs [--debug]   (needs ANDROID_HOME and JDK 21; see scripts/setup-android-sdk.sh)
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// mobile project folder; this script lives in mobile/scripts
const MOBILE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// gradle project generated by capacitor
const ANDROID = join(MOBILE, "android");
// shared artifact folder for every platform build
const RELEASE_DIR = resolve(MOBILE, "..", "release");

// runs a command through the shell (npx and gradlew.bat need it on windows) and aborts on failure
function run(command, cwd) {
  console.log(`[apk] ${command}`);
  const res = spawnSync(command, { cwd, stdio: "inherit", shell: true });
  if (res.status !== 0) throw new Error(`${command} failed with exit code ${res.status}`);
}

// release when a keystore is configured (and --debug was not passed), debug otherwise
function main() {
  const sdk = process.env.ANDROID_HOME ?? process.env.ANDROID_SDK_ROOT;
  if (!sdk && !existsSync(join(ANDROID, "local.properties")))
    throw new Error("ANDROID_HOME is not set; run scripts/setup-android-sdk.sh and export ANDROID_HOME");
  const keystore = process.env.ANDROID_KEYSTORE_PATH;
  const release = !process.argv.includes("--debug") && !!keystore;
  if (keystore && !existsSync(keystore)) throw new Error(`ANDROID_KEYSTORE_PATH points to a missing file: ${keystore}`);
  if (!release) console.log("[apk] ANDROID_KEYSTORE_PATH not set (or --debug): building a debug-signed apk");

  const { version } = JSON.parse(readFileSync(join(MOBILE, "package.json"), "utf8"));
  run("node scripts/copy-web.mjs", MOBILE);
  run("npx cap sync android", MOBILE);
  const gradlew = process.platform === "win32" ? "gradlew.bat" : "./gradlew";
  run(`${gradlew} --no-daemon ${release ? "assembleRelease" : "assembleDebug"}`, ANDROID);

  const built = release
    ? join(ANDROID, "app", "build", "outputs", "apk", "release", "app-release.apk")
    : join(ANDROID, "app", "build", "outputs", "apk", "debug", "app-debug.apk");
  if (!existsSync(built)) throw new Error(`expected apk not found: ${built}`);
  mkdirSync(RELEASE_DIR, { recursive: true });
  const target = join(RELEASE_DIR, release ? `HL-Quant-${version}.apk` : `HL-Quant-${version}-debug.apk`);
  copyFileSync(built, target);
  console.log(`[apk] ${target} (${(statSync(target).size / 1048576).toFixed(1)} MiB)`);
}

main();
